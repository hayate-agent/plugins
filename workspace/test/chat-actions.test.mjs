import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import os from 'node:os';
import path from 'node:path';
import { Workspace } from '../service.mjs';
import { WebUIChannel } from '../../dashboard-api/index.mjs';
import { workspaceRequest } from '../../agent-link/workspace-protocol.mjs';

test('HTTP and Agent-Link forks retain independent context with ownership and sharing checks', async t => {
  const home = await mkdtemp(path.join(os.tmpdir(), 'chat-actions-'));
  const workspace = new Workspace({ home, cwd: home, executionContexts: { async bind() {} } });
  await workspace.open();
  const delivered = [];
  await workspace.channel.start(async input => delivered.push(input));
  const channel = new WebUIChannel({ home, port: 0, services: { get: name => name === 'workspaces' ? { version: 1, implementation: workspace } : undefined } });
  await channel.start(async () => {});
  t.after(async () => { await channel.stop(); await workspace.stop(); await rm(home, { recursive: true, force: true }); });
  const source = await workspace.createStream('operator', { title: 'Original' });
  await workspace.submit('operator', source.id, { id: randomUUID(), text: 'Remember cobalt' });
  await workspace.channel.send({ target: source.id }, 'Cobalt remembered');
  const post = (route, body, origin = channel.url) => fetch(channel.url + '/api/workspace' + route, { method: 'POST', headers: { Origin: origin, 'X-Hayate-WebUI': '1', 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const key = randomUUID();
  assert.equal((await post(`/streams/${source.id}/fork`, { idempotencyKey: key }, 'https://untrusted.example')).status, 403);
  const response = await post(`/streams/${source.id}/fork`, { idempotencyKey: key });
  assert.equal(response.status, 201);
  const local = await response.json();
  assert.deepEqual(local.messages, JSON.parse(JSON.stringify(workspace.stream('operator', source.id).messages)));
  assert.equal((await (await post(`/streams/${source.id}/fork`, { idempotencyKey: key })).json()).id, local.id);
  assert.equal(delivered.length, 1, 'Fork creation never replays a message');
  const foreign = await workspace.createStream('other', { title: 'Private' });
  assert.notEqual((await post(`/streams/${foreign.id}/fork`, { idempotencyKey: randomUUID() })).status, 201);
  const input = { action: 'fork', streamId: source.id, idempotencyKey: randomUUID() };
  await assert.rejects(workspaceRequest(workspace, {}, 'operator', 'streams', input), /refused/);
  const config = { shareStandalone: true };
  const remote = await workspaceRequest(workspace, config, 'operator', 'streams', input);
  assert.equal((await workspaceRequest(workspace, config, 'operator', 'streams', input)).id, remote.id);
  await assert.rejects(workspaceRequest(workspace, config, 'other', 'streams', input), /not found/);
  await workspaceRequest(workspace, config, 'operator', 'streams', { action: 'rename', streamId: remote.id, title: 'Independent' });
  assert.equal(workspace.stream('operator', source.id).title, 'Original');
  assert.equal(workspace.stream('operator', remote.id).title, 'Independent');
  assert.equal(delivered.length, 1);
  await workspace.submit('operator', local.id, { id: randomUUID(), text: 'Local continuation' });
  await workspaceRequest(workspace, config, 'operator', 'messages', { action: 'send', streamId: remote.id, id: randomUUID(), text: 'Remote continuation' });
  assert.equal(workspace.stream('operator', source.id).messages.length, 2);
  assert.equal(workspace.stream('operator', local.id).messages.length, 3);
  assert.equal(workspace.stream('operator', remote.id).messages.length, 3);
  assert.equal(delivered.length, 3);
  for (const turn of delivered.slice(1)) assert.match(JSON.stringify(turn), /Remember cobalt/);
});
