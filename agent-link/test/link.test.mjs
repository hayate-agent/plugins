test('two headless instances pair over verified TLS, scope projects, exchange work and revoke real target authorization', async t => {
  const f = await setup(t);
  const issued = await f.target.issueCode('operator', { name: 'Target', capabilities: ['projects', 'streams', 'messages', 'activity'] });
  const agent = await f.central.connect('operator', { adapter: 'hayate', endpoint: f.origin, code: issued.code, name: 'Remote target', color: '#112233' });
  assert.equal(agent.remoteAgent, 'Target Hayate');
  await assert.rejects(f.adapter.pair({ endpoint: f.origin, code: issued.code }), /refused/);
  const dashboard = await f.central.projectDashboard('operator', 'central-project');
  assert.equal(dashboard.agents[0].status, 'connected'); assert.equal(dashboard.agents[0].projectId, f.project.id);
  assert.equal((await f.central.projectDashboard('operator', 'unknown-project')).agents[0].status, 'not-shared');
  const list = await f.central.request('operator', agent.id, 'projects', { action: 'list' });
  assert.equal(list.projects.length, 1); assert.equal(list.projects[0].id, f.project.id);
  const receipts = await f.central.syncProject('operator', { id: 'central-project', title: 'Shared project', settings: { model: 'provider/model' } });
  assert.equal(receipts[0].ok, true); assert.equal(f.workspace.snapshot('operator').projects[0].title, 'Shared project');
  const creation = { action: 'create', projectId: f.project.id, title: 'Remote work', idempotencyKey: randomUUID() };
  const [stream, duplicate] = await Promise.all([f.central.request('operator', agent.id, 'streams', creation), f.central.request('operator', agent.id, 'streams', creation)]);
  assert.equal(duplicate.id, stream.id); assert.equal(f.workspace.snapshot('operator').streams.length, 1);
  await assert.rejects(f.central.request('operator', agent.id, 'streams', { ...creation, title: 'Different work' }), /refused/);
  assert.equal(f.bindings.get(`plugin:workspaces:${stream.id}`).cwd, f.targetHome);
  await f.central.request('operator', agent.id, 'messages', { action: 'send', streamId: stream.id, id: randomUUID(), text: 'Do work' });
  assert.equal(f.received.length, 1); assert.equal(f.received[0].turn.model, 'provider/model');
  const conversation = await f.central.request('operator', agent.id, 'messages', { action: 'read', streamId: stream.id });
  assert.equal(conversation.messages.at(-1).text, 'Remote answer');
  await f.central.request('operator', agent.id, 'messages', { action: 'mark-read', streamId: stream.id });
  const updated = await f.central.projectDashboard('operator', 'central-project'); assert.equal(updated.agents[0].streams.length, 1);
  await assert.rejects(f.central.request('operator', agent.id, 'streams', { action: 'create', projectId: f.other.id }), /refused/);
  await assert.rejects(f.central.request('operator', agent.id, 'streams', { action: 'move', streamId: stream.id, projectId: f.other.id }), /refused/);
  await assert.rejects(f.central.request('operator', agent.id, 'streams', { action: 'move', streamId: stream.id, projectId: null }), /refused/);
  const original = structuredClone(f.bindings.get(`plugin:workspaces:${stream.id}`));
  await f.central.request('operator', agent.id, 'streams', { action: 'move', streamId: stream.id, projectId: f.project.id });
  assert.deepEqual(f.bindings.get(`plugin:workspaces:${stream.id}`), original);
  f.server.config.shareStandalone = true;
  const standalone = await f.central.request('operator', agent.id, 'streams', { action: 'create', projectId: null, title: 'Standalone', idempotencyKey: randomUUID() });
  assert.equal(standalone.projectId, null);
  await f.central.request('operator', agent.id, 'streams', { action: 'move', streamId: standalone.id, projectId: f.project.id });
  assert.equal(f.workspace.stream('operator', standalone.id).projectId, f.project.id);
  await f.central.request('operator', agent.id, 'streams', { action: 'move', streamId: standalone.id, projectId: null });
  assert.equal(f.workspace.stream('operator', standalone.id).projectId, null);
  assert.ok((await f.central.request('operator', agent.id, 'streams', { action: 'list' })).features.includes('standalone-chats'));
  const credential = f.central.store.read().agents[0].credential;
  await f.central.credentials.withSecret('operator', credential, async token => {
    assert.equal((await readFile(path.join(f.targetHome, 'agent-link/peers.json'), 'utf8')).includes(token), false);
    assert.equal((await readFile(path.join(f.centralHome, 'agent-hub/state.json'), 'utf8')).includes(token), false);
    assert.equal(JSON.stringify(f.central.list('operator')).includes(token), false);
  });
  assert.equal(f.server.list().length, 1);
  await f.central.remove('operator', agent.id); assert.equal(f.server.list().length, 0); assert.equal(f.central.list('operator').length, 0);
});

test('actual target Core accepts remote work once and delivers the persisted reply without WebUI', { skip: !process.env.HARNESS_CORE_ROOT }, async t => {
  const root = path.resolve(process.env.HARNESS_CORE_ROOT);
  const load = file => import(pathToFileURL(path.join(root, file)).href);
  const { Harness } = await load('src/harness.ts'); const { PluginHost } = await load('src/plugins.ts'); const { FakeRuntime } = await load('test/fakes.ts');
  const { ExecutionContexts } = await load('src/execution-contexts.ts');
  const f = await setup(t); await f.server.stop();
  const runtime = new FakeRuntime(); const host = new PluginHost();
  const harness = new Harness({ runtime, tickMs: 60000, updateBlockers: () => host.updateBlockers() });
  const contexts = new ExecutionContexts(path.join(f.targetHome, 'contexts.json'), f.targetHome); await contexts.load();
  await writeFile(path.join(f.targetHome, 'agent-link.json'), JSON.stringify({ peers: [{ origin: f.origin, caFile: f.config.certFile }], listen: f.config }));
  await writeFile(path.join(f.targetHome, 'agent-hub.json'), JSON.stringify({ adapters: ['hayate'] }));
  const files = ['credentials/index.mjs', 'workspace/index.mjs', 'agent-link/index.mjs', 'agent-hub/index.mjs', 'agent-link/server.mjs'].map(file => fileURLToPath(new URL('../../' + file, import.meta.url)));
  await host.load(files, { home: f.targetHome, cwd: f.targetHome, agent: 'Target', executionContexts: { get: key => contexts.get(key), bind: (key, value) => harness.withForegroundWork(() => contexts.bind(key, value)) }, foregroundWork: work => harness.withForegroundWork(work) }, []);
  for (const channel of host.channels.values()) harness.addChannel(channel);
  await harness.start();
  t.after(async () => { await harness.stop(); await host.stop(); });
  const issued = await host.services.get('agent-hub').implementation.issueCode('operator', { name: 'Target', capabilities: ['streams', 'messages'] });
  const agent = await f.central.connect('operator', { adapter: 'hayate', endpoint: f.origin, code: issued.code, name: 'Target Core' });
  const stream = await f.central.request('operator', agent.id, 'streams', { action: 'create', projectId: f.project.id, title: 'Actual host work' });
  const message = { action: 'send', streamId: stream.id, id: randomUUID(), text: 'Inspect target checkout' };
  await f.central.request('operator', agent.id, 'messages', message); await harness.drained();
  await f.central.request('operator', agent.id, 'messages', message); await harness.drained();
  assert.equal(runtime.sessions.get(`plugin:workspaces:${stream.id}`).prompts.length, 1);
  assert.equal(contexts.get(`plugin:workspaces:${stream.id}`).cwd, f.targetHome);
  const response = await f.central.request('operator', agent.id, 'messages', { action: 'read', streamId: stream.id });
  assert.equal(response.messages.filter(message => message.role === 'assistant').length, 1);
  assert.equal(response.unread, true);
  assert.equal(harness.acquireUpdateAdmission(1000).status, 'admitted');
});

test('untrusted TLS, unconfigured destinations and insufficient capabilities fail closed', async t => {
  const f = await setup(t);
  const issued = await f.target.issueCode('operator', { name: 'Read activity', capabilities: ['activity'] });
  await assert.rejects(new HayateAdapter([{ origin: f.origin }]).pair({ endpoint: f.origin, code: issued.code }), /failed/);
  await assert.rejects(new HayateAdapter([]).pair({ endpoint: f.origin, code: issued.code }), /allowlist/);
  assert.throws(() => new HayateAdapter([{ origin: 'http://localhost' }]), /HTTPS/);
  const agent = await f.central.connect('operator', { adapter: 'hayate', endpoint: f.origin, code: issued.code, name: 'Activity-only target' });
  await assert.rejects(f.central.request('operator', agent.id, 'messages', { action: 'send' }), /unavailable/);
  assert.equal((await f.central.request('operator', agent.id, 'activity', { action: 'list' })).streams.length, 0);
  await f.server.store.change(data => { data.peers[0].expiresAt = Date.now() - 1; });
  await assert.rejects(f.central.request('operator', agent.id, 'activity', { action: 'list' }), /refused/);
  await f.server.revoke(f.server.list()[0].id);
  await assert.rejects(f.central.request('operator', agent.id, 'activity', { action: 'list' }), /refused/);
  await f.central.remove('operator', agent.id); assert.equal(f.central.list('operator').length, 0, 'Revoke is safely idempotent after target-side revocation');
});
